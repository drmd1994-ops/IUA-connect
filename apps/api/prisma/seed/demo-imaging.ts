export async function seedDemoImaging(prisma: PrismaClient): Promise<void> {
  if (await prisma.educationItem.findUnique({ where: { slug: SCANS[0]!.slug } })) {
    console.log('seed: demo teaching scans already present, skipped');
    return;
  }
  const editor = (
    await prisma.user.findUnique({ where: { email: 'editor@demo.test' }, select: { id: true } })
  )?.id;
  if (!editor) {
    console.log('seed: demo teaching scans need the demo people first, skipped');
    return;
  }

  const response = await fetch(RELEASE);
  if (!response.ok) throw new Error(`The demo scans could not be downloaded (${response.status})`);
  const archive = Buffer.from(await response.arrayBuffer());
  const sha256 = createHash('sha256').update(archive).digest('hex');
  if (sha256 !== SHA256)
    throw new Error(`The demo scans' SHA-256 is ${sha256}, expected ${SHA256}`);
  const work = mkdtempSync(path.join(tmpdir(), 'medconnect-demo-scans-'));
  try {
    // Unpacked from inside the folder by a plain name: no drive letter for tar to misread.
    writeFileSync(path.join(work, 'scans.tar.gz'), archive);
    execFileSync('tar', ['-xzf', 'scans.tar.gz'], { cwd: work });
    for (const seed of SCANS) await addScan(prisma, seed, path.join(work, seed.folder), editor);
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
  console.log(`seed: ${SCANS.length} demo teaching scans, waiting for review`);
}

async function addScan(prisma: PrismaClient, seed: ScanSeed, folder: string, editor: string) {
  const subspecialty = await prisma.subspecialty.findUnique({
    where: { key: seed.subspecialty },
    select: { id: true },
  });
  if (!subspecialty) throw new Error(`Unknown subspecialty: ${seed.subspecialty}`);

  // Cleaned and stored like an upload (imaging.service.ts), one file at a time.
  const today = new Date();
  const month = `${today.getUTCFullYear()}/${String(today.getUTCMonth() + 1).padStart(2, '0')}`;
  const root = path.resolve(REPO_ROOT, process.env.STORAGE_DIR ?? 'storage');
  const uids = new Map<string, string>();
  const stored: (Omit<CleanInstance, 'body'> & { id: string; key: string; size: number })[] = [];
  for (const name of readdirSync(folder)
    .filter((f) => f.endsWith('.dcm'))
    .sort()) {
    const { instance } = deidentify(readFileSync(path.join(folder, name)), uids);
    const id = uuidv7();
    const key = `${month}/${id}`;
    const file = path.join(root, ...key.split('/'));
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, instance.body, { flag: 'wx' });
    const { body, ...rest } = instance;
    stored.push({ ...rest, id, key, size: body.length });
  }

  await prisma.$transaction(async (tx: Prisma.TransactionClient) => {
    const itemId = uuidv7();
    await tx.educationItem.create({
      data: {
        id: itemId,
        slug: seed.slug,
        type: 'CASE',
        status: 'IN_REVIEW',
        level: 'RESIDENT',
        subspecialtyId: subspecialty.id,
        accessTier: 'VERIFIED',
        references: seed.references,
        authorUserId: editor,
        submittedBy: editor,
        translations: {
          create: [
            { locale: 'he', ...seed.he },
            { locale: 'en', ...seed.en },
          ],
        },
      },
    });
    for (const [action, fromStatus, toStatus] of [
      ['create', null, 'DRAFT'],
      ['SUBMIT', 'DRAFT', 'IN_REVIEW'],
    ] as const) {
      await tx.educationHistory.create({
        data: { id: uuidv7(), itemId, action, fromStatus, toStatus, actorUserId: editor },
      });
    }
    const scanId = uuidv7();
    const seriesId = uuidv7();
    await tx.scan.create({
      data: {
        id: scanId,
        ownerUserId: editor,
        educationItemId: itemId,
        studyUid: stored[0]!.studyUid,
        modalities: stored[0]!.modality,
        instanceCount: stored.length,
        sizeBytes: stored.reduce((sum, s) => sum + s.size, 0),
        attachedAt: new Date(),
      },
    });
    await tx.scanSeries.create({
      data: {
        id: seriesId,
        scanId,
        seriesUid: stored[0]!.seriesUid,
        modality: stored[0]!.modality,
        number: stored[0]!.seriesNumber,
        instanceCount: stored.length,
      },
    });
    await tx.scanInstance.createMany({
      data: stored.map((s) => ({
        id: s.id,
        seriesId,
        sopInstanceUid: s.sopInstanceUid,
        sopClassUid: s.sopClassUid,
        number: s.instanceNumber,
        storageKey: s.key,
        sizeBytes: s.size,
        metadata: s.metadata as Prisma.InputJsonValue,
      })),
    });
  });
}
