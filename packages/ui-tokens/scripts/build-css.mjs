// Generates dist/tokens.css (a Tailwind v4 @theme block) from the compiled token module.
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const tokens = require('../dist/index.js');

const kebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const lines = [];

for (const [scale, shades] of Object.entries(tokens.colors)) {
  for (const [shade, value] of Object.entries(shades)) {
    lines.push(`  --color-${scale}-${shade}: ${value};`);
  }
}
for (const [name, value] of Object.entries(tokens.semantic)) {
  lines.push(`  --color-${kebab(name)}: ${value};`);
}
for (const [name, value] of Object.entries(tokens.radii)) {
  lines.push(`  --radius-${name}: ${value};`);
}
for (const [name, value] of Object.entries(tokens.fontSizes)) {
  lines.push(`  --text-${name}: ${value};`);
}
for (const [name, value] of Object.entries(tokens.fonts)) {
  lines.push(`  --font-${name}: ${value};`);
}
for (const [name, value] of Object.entries(tokens.shadows)) {
  lines.push(`  --shadow-${name}: ${value};`);
}

const css = `/* Generated by @iua/ui-tokens. Do not edit; change src/index.ts instead. */\n@theme {\n${lines.join('\n')}\n}\n`;
writeFileSync(new URL('../dist/tokens.css', import.meta.url), css);
